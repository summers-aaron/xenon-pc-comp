// xfxc: minimal FXC stand-in for building Xenia/ReXGlue Direct3D 12 shaders on
// a Windows machine without the Windows SDK. Compiles one HLSL/XESL file to
// Shader Model 5.1 DXBC with d3dcompiler_47.dll (part of Windows) using the
// flags of Xenia's tools/build/compile_shader_dxbc.py, and writes an
// `fxc /Fh`-style header:  const BYTE <name>[] = { ... };
//
//   xfxc.exe <input> <output.h> <target, e.g. cs_5_1> <variable name>
//
// Equivalent FXC flags: /D SHADING_LANGUAGE_HLSL_XE=1 /I <input dir> /O3 /Gfp
// /Qstrip_reflect /Qstrip_debug /Qstrip_priv.
#define WIN32_LEAN_AND_MEAN
#include <windows.h>

#include <d3dcompiler.h>
#include <stdio.h>
#include <wchar.h>

static wchar_t* Widen(const char* s) {
  int n = MultiByteToWideChar(CP_UTF8, 0, s, -1, NULL, 0);
  wchar_t* w = (wchar_t*)HeapAlloc(GetProcessHeap(), 0, n * sizeof(wchar_t));
  MultiByteToWideChar(CP_UTF8, 0, s, -1, w, n);
  return w;
}

int main(int argc, char** argv) {
  if (argc != 5) {
    fprintf(stderr, "usage: %s <input> <output.h> <target> <variable>\n", argv[0]);
    return 2;
  }
  const D3D_SHADER_MACRO defines[] = {{"SHADING_LANGUAGE_HLSL_XE", "1"}, {NULL, NULL}};
  ID3DBlob* code = NULL;
  ID3DBlob* errors = NULL;
  // The standard include handler resolves #include relative to the including
  // file, which covers FXC's /I <input dir>.
  HRESULT hr = D3DCompileFromFile(Widen(argv[1]), defines, D3D_COMPILE_STANDARD_FILE_INCLUDE,
                                  "main", argv[3],
                                  D3DCOMPILE_OPTIMIZATION_LEVEL3 | D3DCOMPILE_PREFER_FLOW_CONTROL,
                                  0, &code, &errors);
  if (errors) {
    fwrite(errors->lpVtbl->GetBufferPointer(errors), 1, errors->lpVtbl->GetBufferSize(errors),
           stderr);
  }
  if (FAILED(hr)) {
    fprintf(stderr, "xfxc: %s failed (0x%08lX)\n", argv[1], (unsigned long)hr);
    return 1;
  }
  ID3DBlob* stripped = NULL;
  hr = D3DStripShader(code->lpVtbl->GetBufferPointer(code), code->lpVtbl->GetBufferSize(code),
                      D3DCOMPILER_STRIP_REFLECTION_DATA | D3DCOMPILER_STRIP_DEBUG_INFO |
                          D3DCOMPILER_STRIP_PRIVATE_DATA,
                      &stripped);
  if (FAILED(hr)) {
    fprintf(stderr, "xfxc: stripping %s failed (0x%08lX)\n", argv[1], (unsigned long)hr);
    return 1;
  }
  FILE* out = fopen(argv[2], "wb");
  if (!out) {
    fprintf(stderr, "xfxc: cannot write %s\n", argv[2]);
    return 1;
  }
  const unsigned char* bytes = (const unsigned char*)stripped->lpVtbl->GetBufferPointer(stripped);
  size_t size = stripped->lpVtbl->GetBufferSize(stripped);
  fprintf(out, "// Generated by xfxc (d3dcompiler_47, %s) from %s.\n\nconst BYTE %s[] =\n{\n",
          argv[3], argv[1], argv[4]);
  for (size_t i = 0; i < size; ++i) {
    fprintf(out, "%s%3u%s", i % 16 ? "" : "    ", bytes[i],
            i + 1 == size ? "\n" : (i % 16 == 15 ? ",\n" : ", "));
  }
  fprintf(out, "};\n");
  fclose(out);
  return 0;
}
