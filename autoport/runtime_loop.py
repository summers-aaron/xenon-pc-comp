#!/usr/bin/env python3
"""Run the recompiled game, harvest missed indirect-call targets, regenerate, rebuild.

Each iteration:
  1. run the executable for --seconds with logging
  2. parse "[FATAL] Call to invalid or unregistered function at guest address X"
  3. map X to its module via "Function table initialized for module" ranges
  4. append `0xX = {}` to that module's config/<stem>_auto.toml
  5. fix_unresolved.py (codegen + tail-merge fixes), gen_xdll_imports.py, rebuild
Stops when a run ends without a new FATAL address.

With --windows-stage DIR (a /mnt/<drive> path under WSL) the build is a Windows
cross-build: each iteration copies the .exe/.dlls to DIR and runs them on
Windows through WSL interop.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
RE_FATAL = re.compile(r"\[FATAL\] (?:Call to invalid or unregistered function at guest address|Unresolved call from 0x[0-9A-Fa-f]+ to) 0x([0-9A-Fa-f]+)")
RE_TABLE = re.compile(r"Function table initialized for module: code=([0-9A-F]+)-([0-9A-F]+), image=([0-9A-F]+)-([0-9A-F]+)")
RE_REGISTER = re.compile(r"Registering module: (\S+) \(code_base=([0-9A-F]+)\)")


def sh(cmd, log, cwd=None, env=None, timeout=None):
    with open(log, "w") as f:
        try:
            return subprocess.run(cmd, cwd=cwd, env=env, stdout=f, stderr=subprocess.STDOUT,
                                  timeout=timeout).returncode
        except subprocess.TimeoutExpired:
            return None


def win_path(path):
    return subprocess.run(["wslpath", "-w", str(path)], capture_output=True, text=True,
                          check=True).stdout.strip()


def stage_windows(build_dir, stage):
    """Copy the executable and DLLs that changed since the last run."""
    stage.mkdir(parents=True, exist_ok=True)
    for f in [*build_dir.glob("*.exe"), *build_dir.glob("*.dll")]:
        dst = stage / f.name
        if not dst.exists() or dst.stat().st_mtime < f.stat().st_mtime:
            shutil.copy2(f, dst)


def module_for(addr, runlog, manifest):
    """Return the manifest file_path stem owning addr."""
    data = tomllib.loads(manifest.read_text())
    code_bases = {int(b, 16): name for name, b in RE_REGISTER.findall(runlog)}
    for lo, hi, ilo, ihi in RE_TABLE.findall(runlog):
        if int(ilo, 16) <= addr < int(ihi, 16):
            guest = code_bases.get(int(lo, 16))
            if guest is None:
                return Path(data["entrypoint"]["file_path"]).stem
            for m in data.get("modules", []):
                if m["guest_path"].lower() == guest.lower():
                    return Path(m["file_path"]).stem
    return None


def add_function(manifest, stem, addr):
    inc = manifest.parent / "config" / f"{stem.lower()}_auto.toml"
    text = inc.read_text() if inc.exists() else "# Auto-generated by autoport\n\n[functions]\n"
    key = f"0x{addr:08X} = {{}}"
    if key in text:
        return False
    inc.parent.mkdir(exist_ok=True)
    inc.write_text(text + f"{key}  # runtime: unregistered indirect call target\n")
    # Make sure the manifest includes it (fix_unresolved.module_include does the same).
    sys.path.insert(0, str(HERE))
    from fix_unresolved import module_include
    module_include(manifest, stem)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    ap.add_argument("--rexglue", required=True)
    ap.add_argument("--sdk-lib", required=True)
    ap.add_argument("--build-dir", required=True, type=Path)
    ap.add_argument("--build-cmd", required=True, help="shell command that rebuilds the project")
    ap.add_argument("--exe", required=True)
    ap.add_argument("--run-args", default="")
    ap.add_argument("--seconds", type=int, default=60)
    ap.add_argument("--max-iter", type=int, default=25)
    ap.add_argument("--windows-stage", type=Path,
                    help="run a Windows build from this directory (WSL path) via interop")
    args = ap.parse_args()
    manifest = args.manifest.resolve()
    root = manifest.parent
    logs = root / "autoport_logs"
    logs.mkdir(exist_ok=True)

    env = dict(os.environ)
    env["LD_LIBRARY_PATH"] = f"{args.build_dir}:{args.sdk_lib}"
    env.setdefault("SDL_VIDEODRIVER", "offscreen")  # headless: GPU emulation still runs on Vulkan

    for it in range(args.max_iter):
        if args.windows_stage:
            stage = args.windows_stage
            stage_windows(args.build_dir, stage)
            (stage / "autoport-logs").mkdir(exist_ok=True)
            runlog = stage / "autoport-logs" / f"run{it}.log"
            runlog.unlink(missing_ok=True)
            exe = stage / args.exe
            rc = sh([str(exe), f"--log_file={win_path(runlog)}", *args.run_args.split()],
                    logs / f"run{it}.out", cwd=stage, timeout=args.seconds)
            if rc is None:  # the interop proxy is gone, the Windows process is not
                subprocess.run(["taskkill.exe", "/F", "/T", "/IM", exe.name],
                               capture_output=True)
        else:
            runlog = logs / f"run{it}.log"
            runlog.unlink(missing_ok=True)
            rc = sh([str(args.build_dir / args.exe), f"--log_file={runlog}", *args.run_args.split()],
                    logs / f"run{it}.out", cwd=args.build_dir, env=env, timeout=args.seconds)
        text = runlog.read_text(errors="replace") if runlog.exists() else ""
        fatals = RE_FATAL.findall(text)
        if not fatals:
            status = "still running at timeout" if rc is None else f"exited rc={rc}"
            print(f"[iter {it}] no unregistered-call FATAL ({status}); stopping")
            return 0
        addr = int(fatals[-1], 16)
        stem = module_for(addr, text, manifest)
        if stem is None or not add_function(manifest, stem, addr):
            print(f"[iter {it}] FATAL at 0x{addr:08X} not auto-fixable (module={stem})")
            return 1
        print(f"[iter {it}] {stem}: added function 0x{addr:08X}")

        if subprocess.run([sys.executable, HERE / "fix_unresolved.py", manifest, "--rexglue", args.rexglue]).returncode:
            return 1
        if subprocess.run([sys.executable, HERE / "gen_xdll_imports.py", manifest,
                           "--log", root / "codegen_auto.log"]).returncode:
            return 1
        if subprocess.run([sys.executable, HERE / "patch_spin_hints.py", manifest]).returncode:
            return 1
        if sh(["bash", "-c", args.build_cmd], logs / f"build{it}.log", cwd=root):
            print(f"[iter {it}] build failed; see {logs / f'build{it}.log'}")
            return 1
        if not args.windows_stage:
            subprocess.run(["bash", "-c", "for f in lib*.so; do n=${f#lib}; ln -sf $f ${n%.so}; done"],
                           cwd=args.build_dir)
    return 1


if __name__ == "__main__":
    sys.exit(main())
